#!/usr/bin/env python3
"""
region_analysis.py -- Stage 1 of "Algebraic Machine Reasoning on MissionReason".

Question: after discretizing the MissionReason expert-policy state at the
policy's OWN thresholds, is each decision region a monomial concept, and what are
its minimal generators (= minimal sufficient attribute patterns)?

Pipeline
  1. Discretize the 7 policy inputs into bins (edges aligned with the policy's
     breakpoints, see DEFAULT_EDGES).  Each bin is one variable of the ring.
  2. A discretized state ("cell") = squarefree monomial with one variable per
     attribute.
  3. Label each cell with the policy decision.  A cell is PURE if the policy
     returns one action everywhere inside it, MIXED otherwise.
        Exactness argument: inside a cell, every action utility is linear in the
        continuous inputs (bin edges include the policy breakpoints 0/50/80/100
        for cloud and 0 / 15 for ground contact), so each action's region is
        convex; hence a box is pure iff all of its corners agree.  We nevertheless
        validate empirically with random states (--samples).
  4. For each action A, the decision-region concept is
        J_A = < p : p is a partial pattern all of whose completions are pure-A >,
     generated by the minimal such patterns (prime implicants).
  5. Algebra: attribute-level necessary conditions (components inside one
     attribute concept J_l), and optionally the full minimal primes.

Usage
  python region_analysis.py --repo /path/to/mission-reason [--out results]
"""
from __future__ import annotations

import argparse
import importlib.util
import itertools
import json
import random
import sys
import time
from collections import Counter
from pathlib import Path
from typing import Dict, List, Sequence, Tuple

import numpy as np

import mr_algebra as alg

# ----------------------------------------------------------------------------
# Discretization spec (mirrors scenarios.py ranges and optimization_rules.py)
# ----------------------------------------------------------------------------
CATEGORICAL: Dict[str, List[str]] = {
    "mission_type": ["Earth Observation", "Wildfire Monitoring", "Agriculture",
                     "Disaster Response", "Ocean Monitoring"],
    "temperature": ["Normal", "High", "Critical"],
    "target_priority": ["Low", "Medium", "High", "Critical"],
}
# inclusive integer ranges used by scenarios.generate_random_state
NUMERIC_RANGE: Dict[str, Tuple[int, int]] = {
    "battery_level": (0, 100),
    "memory_usage": (0, 100),
    "cloud_probability": (0, 100),
    "ground_contact": (0, 30),
}
# Bin edges (half-open [e_i, e_{i+1}) on integers).  Chosen so that they include
# every breakpoint of the policy: battery 15/30/40; cloud 50/80; ground 0|1, 15.
DEFAULT_EDGES: Dict[str, List[int]] = {
    "battery_level": [0, 15, 30, 40, 101],
    "memory_usage": [0, 25, 50, 75, 101],
    "cloud_probability": [0, 25, 50, 65, 80, 90, 101],
    "ground_contact": [0, 1, 8, 15, 31],
}
ATTR_ORDER = ["mission_type", "battery_level", "memory_usage", "temperature",
              "cloud_probability", "target_priority", "ground_contact"]
UNUSED_FIELD_DEFAULTS = {"remaining_pass_time": 15}  # ignored by the policy


def build_bins(edges: Dict[str, List[int]]):
    """Return per-attribute list of bins: dict(label, lo, hi, weight)."""
    bins: Dict[str, List[dict]] = {}
    for a in ATTR_ORDER:
        if a in CATEGORICAL:
            vals = CATEGORICAL[a]
            bins[a] = [dict(label=v, lo=None, hi=None, weight=1.0 / len(vals)) for v in vals]
        else:
            lo_r, hi_r = NUMERIC_RANGE[a]
            n = hi_r - lo_r + 1
            e = edges[a]
            assert e[0] == lo_r and e[-1] == hi_r + 1, f"edges for {a} must span the range"
            bs = []
            for lo, nxt in zip(e[:-1], e[1:]):
                hi = nxt - 1
                bs.append(dict(label=f"{lo}-{hi}" if hi > lo else f"{lo}",
                               lo=lo, hi=hi, weight=(hi - lo + 1) / n))
            bins[a] = bs
    return bins


def var_name(attr: str, b: dict) -> str:
    return f"{attr}={b['label']}"


def load_policy(repo: Path):
    sys.path.insert(0, str(repo))
    spec = importlib.util.spec_from_file_location("optimization_rules", repo / "optimization_rules.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.evaluate_expert_policy


def policy_action(policy, state: dict) -> str:
    return policy(state)[0]


# ----------------------------------------------------------------------------
# Cell labelling
# ----------------------------------------------------------------------------
def label_cells(policy, bins):
    dims = tuple(len(bins[a]) for a in ATTR_ORDER)
    action_ids: Dict[str, int] = {}
    labels = np.full(dims, -1, dtype=np.int16)         # -1 = MIXED
    mixed_sets: Dict[Tuple[int, ...], Tuple[str, ...]] = {}
    for idx in np.ndindex(*dims):
        base = dict(UNUSED_FIELD_DEFAULTS)
        corner_axes = []
        for a, i in zip(ATTR_ORDER, idx):
            b = bins[a][i]
            if a in CATEGORICAL:
                base[a] = b["label"]
            else:
                corner_axes.append((a, sorted({b["lo"], b["hi"]})))
        seen = set()
        names = [a for a, _ in corner_axes]
        for combo in itertools.product(*[v for _, v in corner_axes]):
            st = dict(base)
            st.update(dict(zip(names, combo)))
            seen.add(policy_action(policy, st))
        if len(seen) == 1:
            act = next(iter(seen))
            labels[idx] = action_ids.setdefault(act, len(action_ids))
        else:
            for act in seen:
                action_ids.setdefault(act, len(action_ids))
            mixed_sets[idx] = tuple(sorted(seen))
    return labels, action_ids, mixed_sets


def weight_array(bins):
    ws = [np.array([b["weight"] for b in bins[a]]) for a in ATTR_ORDER]
    W = ws[0]
    for w in ws[1:]:
        W = np.multiply.outer(W, w)
    return W


# ----------------------------------------------------------------------------
# Prime implicants via wildcard-padded reductions (vectorised)
# ----------------------------------------------------------------------------
def pad(arr: np.ndarray, reducer: str) -> np.ndarray:
    out = arr
    for ax in range(arr.ndim):
        red = out.all(axis=ax, keepdims=True) if reducer == "all" else out.sum(axis=ax, keepdims=True)
        out = np.concatenate([out, red], axis=ax)
    return out


def minimal_patterns(B: np.ndarray) -> np.ndarray:
    """Boolean mask over wildcard-padded pattern space: minimal sufficient patterns."""
    suff = pad(B, "all")
    nd = suff.ndim
    minimal = suff.copy()
    for ax in range(nd):
        k = suff.shape[ax] - 1                       # wildcard index on this axis
        last = np.take(suff, [k], axis=ax)           # pattern with wildcard at ax
        cond = np.broadcast_to(~last, suff.shape).copy()
        sel = [slice(None)] * nd
        sel[ax] = k
        cond[tuple(sel)] = True                      # not applicable when already wildcard
        minimal &= cond
    minimal[(-1,) * nd] = False                      # drop the empty pattern
    return minimal


def pattern_to_mono(idx, bins) -> alg.Mono:
    vs = []
    for a, i in zip(ATTR_ORDER, idx):
        if i < len(bins[a]):
            vs.append(var_name(a, bins[a][i]))
    return frozenset(vs)


# ----------------------------------------------------------------------------
# Main
# ----------------------------------------------------------------------------
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--repo", required=True, help="path to a checkout of mission-reason")
    ap.add_argument("--out", default="results")
    ap.add_argument("--samples", type=int, default=100000, help="random validation states")
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--full-primes", type=int, default=20000,
                    help="limit for full minimal-prime computation (0 = skip)")
    args = ap.parse_args()

    repo = Path(args.repo)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    policy = load_policy(repo)
    bins = build_bins(DEFAULT_EDGES)
    dims = tuple(len(bins[a]) for a in ATTR_ORDER)
    n_cells = int(np.prod(dims))
    print(f"[1] discretization: {dict(zip(ATTR_ORDER, dims))} -> {n_cells} cells")

    t0 = time.time()
    labels, action_ids, mixed_sets = label_cells(policy, bins)
    inv = {v: k for k, v in action_ids.items()}
    W = weight_array(bins)
    mixed_mask = labels < 0
    mixed_mass = float(W[mixed_mask].sum())
    print(f"[2] labelled cells in {time.time()-t0:.1f}s; "
          f"MIXED cells: {int(mixed_mask.sum())}/{n_cells} "
          f"(mass {mixed_mass:.4%} of the repo's sampling distribution)")

    # ---- empirical validation against the repo's own random generator -------
    sys.path.insert(0, str(repo))
    from scenarios import generate_random_state  # type: ignore
    random.seed(args.seed)
    edges_np = {a: np.array(DEFAULT_EDGES[a][1:]) for a in NUMERIC_RANGE}
    emp = Counter()
    mismatches = 0
    pure_hits = 0
    for _ in range(args.samples):
        s = generate_random_state()
        act = policy_action(policy, s)
        emp[act] += 1
        idx = []
        for a in ATTR_ORDER:
            if a in CATEGORICAL:
                idx.append(CATEGORICAL[a].index(s[a]))
            else:
                idx.append(int(np.searchsorted(edges_np[a], s[a], side="right")))
        lab = labels[tuple(idx)]
        if lab >= 0:
            pure_hits += 1
            if inv[int(lab)] != act:
                mismatches += 1
    print(f"[3] validation on {args.samples} random states: "
          f"{pure_hits/args.samples:.2%} fell in pure cells; "
          f"mismatches in pure cells = {mismatches}")

    # ---- per-action regions -------------------------------------------------
    report = {
        "discretization": {a: [var_name(a, b) for b in bins[a]] for a in ATTR_ORDER},
        "n_cells": n_cells,
        "mixed_cells": int(mixed_mask.sum()),
        "mixed_mass": mixed_mass,
        "validation": {"samples": args.samples, "pure_fraction": pure_hits / args.samples,
                       "mismatches_in_pure_cells": mismatches,
                       "empirical_action_freq": {k: v / args.samples for k, v in emp.items()}},
        "actions": {},
    }
    attr_vars = {a: [var_name(a, b) for b in bins[a]] for a in ATTR_ORDER}
    ideals: Dict[str, List[alg.Mono]] = {}

    for aid in sorted(inv):
        act = inv[aid]
        B = labels == aid
        mass = float(W[B].sum())
        t1 = time.time()
        minimal = minimal_patterns(B)
        Wpad = pad(W, "sum")
        pats = np.argwhere(minimal)
        gens = [pattern_to_mono(tuple(p), bins) for p in pats]
        gens = alg.minimalize(gens)
        ideals[act] = gens
        # coverage (mass) of each minimal pattern
        cover = []
        for p in pats:
            m = pattern_to_mono(tuple(p), bins)
            cover.append((float(Wpad[tuple(p)]), len(m), m))
        cover.sort(key=lambda t: (-t[0], t[1]))
        comps = alg.attribute_components(gens, attr_vars)
        necessary = {}
        for a, S in comps.items():
            if S is not None and len(S) < len(attr_vars[a]):
                necessary[a] = sorted(S)
        # brute-force cross-check of the algebraic necessary conditions
        for a_i, a in enumerate(ATTR_ORDER):
            proj = set(np.where(B.any(axis=tuple(j for j in range(B.ndim) if j != a_i)))[0])
            proj_vars = {var_name(a, bins[a][i]) for i in proj}
            S = comps[a]
            if S is not None:
                assert set(S) == proj_vars, (act, a, S, proj_vars)
            else:
                assert len(proj_vars) == len(attr_vars[a]), (act, a)
        sizes = Counter(len(g) for g in gens)
        entry = {
            "cells_pure": int(B.sum()),
            "mass": mass,
            "n_minimal_generators": len(gens),
            "generator_size_histogram": dict(sorted(sizes.items())),
            "necessary_attribute_conditions": necessary,
            "top_patterns_by_mass": [
                {"mass": m, "size": s, "pattern": sorted(mono)} for m, s, mono in cover[:12]],
            "shortest_patterns": [sorted(g) for g in sorted(gens, key=lambda g: (len(g), sorted(g)))[:8]],
        }
        # optional: full minimal primes (can be exponential)
        if args.full_primes and len(gens) <= 400:
            try:
                primes = alg.minimal_primes(gens, limit=args.full_primes)
                ok = alg.check_decomposition(gens, primes) if len(primes) <= 200 else None
                entry["full_minimal_primes"] = {"count": len(primes), "verified": ok,
                                                "sizes": dict(sorted(Counter(len(p) for p in primes).items()))}
            except alg.TooManyTransversals as e:
                entry["full_minimal_primes"] = {"count": None, "note": f"intractable under limit ({e})"}
        elif args.full_primes:
            entry["full_minimal_primes"] = {"count": None, "note": f"skipped ({len(gens)} generators)"}
        report["actions"][act] = entry
        print(f"[4] {act:<9} cells={entry['cells_pure']:>6}  mass={mass:6.2%}  "
              f"min.generators={len(gens):>5}  sizes={entry['generator_size_histogram']}  "
              f"({time.time()-t1:.1f}s)")

    # ---- the sanity check that matters: Emergency -----------------------------
    em = set(ideals.get("Emergency", []))
    expected = {frozenset(["temperature=Critical"]), frozenset(["battery_level=0-14"])}
    report["emergency_matches_policy_source"] = (em == expected)
    print(f"[5] Emergency ideal == <temperature=Critical, battery_level=0-14> : {em == expected}")

    (out / "mr_regions.json").write_text(json.dumps(report, indent=2))
    write_markdown(report, out / "mr_regions.md")
    print(f"wrote {out/'mr_regions.json'} and {out/'mr_regions.md'}")


def write_markdown(rep, path: Path):
    L = []
    L.append("# MissionReason expert policy as monomial concepts (Stage 1)\n")
    L.append(f"- Cells: **{rep['n_cells']}**; MIXED (policy not constant inside the cell): "
             f"**{rep['mixed_cells']}** cells = **{rep['mixed_mass']:.2%}** of the repo's input distribution.")
    v = rep["validation"]
    L.append(f"- Validation on {v['samples']} random states: {v['pure_fraction']:.2%} landed in pure cells; "
             f"mismatches inside pure cells: **{v['mismatches_in_pure_cells']}**.")
    L.append(f"- Emergency ideal equals the policy's hard-override rule: "
             f"**{rep['emergency_matches_policy_source']}**.\n")
    L.append("| Action | pure cells | mass | minimal generators | size histogram |")
    L.append("|---|---:|---:|---:|---|")
    for act, e in rep["actions"].items():
        L.append(f"| {act} | {e['cells_pure']} | {e['mass']:.2%} | {e['n_minimal_generators']} | {e['generator_size_histogram']} |")
    for act, e in rep["actions"].items():
        L.append(f"\n## {act}\n")
        if e["necessary_attribute_conditions"]:
            L.append("Necessary attribute-level conditions (minimal primes inside one attribute concept):\n")
            for a, S in e["necessary_attribute_conditions"].items():
                L.append(f"- `{act}` requires **{a}** in {{{', '.join(s.split('=',1)[1] for s in S)}}}")
        else:
            L.append("No attribute-level necessary condition (every attribute can take every value somewhere in the region).")
        L.append("\nShortest sufficient patterns:\n")
        for g in e["shortest_patterns"]:
            L.append(f"- {' AND '.join(g)}")
        L.append("\nHighest-coverage minimal patterns:\n")
        for t in e["top_patterns_by_mass"][:8]:
            L.append(f"- {t['mass']:.2%}: {' AND '.join(t['pattern'])}")
        if "full_minimal_primes" in e:
            L.append(f"\nFull minimal primes: `{e['full_minimal_primes']}`")
    path.write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
